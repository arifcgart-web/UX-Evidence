-- RPCs
-- ---------------------------------------------------------------------------

-- Accept an invite link. Returns the library id. Anyone signed in with a valid,
-- unexpired, unused token joins with the invite's role.
create or replace function public.accept_invite(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  inv public.invites%rowtype;
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'Sign in first';
  end if;

  select * into inv from public.invites where token = p_token;
  if not found then
    raise exception 'This invite link is not valid';
  end if;
  if inv.accepted_at is not null then
    raise exception 'This invite link has already been used';
  end if;
  if inv.expires_at < now() then
    raise exception 'This invite link has expired';
  end if;

  insert into public.library_members (library_id, user_id, role, email)
  values (inv.library_id, uid, inv.role, coalesce((select email from auth.users where id = uid), ''))
  on conflict (library_id, user_id) do nothing;

  update public.invites set accepted_by = uid, accepted_at = now() where id = inv.id;

  return inv.library_id;
end;
$$;

-- Leave a library you are not the owner of.
create or replace function public.leave_library(p_library uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_owner(p_library) then
    raise exception 'Owners cannot leave their own library. Delete it or transfer ownership.';
  end if;
  delete from public.library_members where library_id = p_library and user_id = auth.uid();
end;
$$;


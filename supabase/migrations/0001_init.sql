alter table public.libraries       enable row level security;
alter table public.library_members enable row level security;
alter table public.invites         enable row level security;
alter table public.evidence        enable row level security;

-- libraries
-- (owner_id check is needed so INSERT ... RETURNING works before the
--  membership trigger has run)
create policy "members can read libraries"
  on public.libraries for select
  using (owner_id = auth.uid() or public.is_member(id));

create policy "anyone signed in can create a library"
  on public.libraries for insert
  with check (auth.uid() = owner_id);

create policy "owners can rename libraries"
  on public.libraries for update
  using (public.is_owner(id))
  with check (public.is_owner(id));

create policy "owners can delete non-personal libraries"
  on public.libraries for delete
  using (public.is_owner(id) and not is_personal);

-- library_members
create policy "members can see who else is in the library"
  on public.library_members for select
  using (public.is_member(library_id));

create policy "owners manage members"
  on public.library_members for update
  using (public.is_owner(library_id))
  with check (public.is_owner(library_id));

create policy "owners remove members, members remove themselves"
  on public.library_members for delete
  using (public.is_owner(library_id) or user_id = auth.uid());

-- (inserts happen only through security-definer functions: triggers and accept_invite)

-- invites
create policy "owners see invites"
  on public.invites for select
  using (public.is_owner(library_id));

create policy "owners create invites"
  on public.invites for insert
  with check (public.is_owner(library_id) and created_by = auth.uid());

create policy "owners revoke invites"
  on public.invites for delete
  using (public.is_owner(library_id));

-- evidence
create policy "members read evidence"
  on public.evidence for select
  using (public.is_member(library_id));

create policy "editors insert evidence"
  on public.evidence for insert
  with check (public.can_edit(library_id));

create policy "editors update evidence"
  on public.evidence for update
  using (public.can_edit(library_id))
  with check (public.can_edit(library_id));

create policy "editors delete evidence"
  on public.evidence for delete
  using (public.can_edit(library_id));

-- ---------------------------------------------------------------------------
-- Storage: private bucket, object path = <library_id>/<evidence_id>/<file>
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('evidence', 'evidence', false, 10485760, array['image/png', 'image/jpeg', 'image/webp'])
on conflict (id) do nothing;

create policy "members read screenshots"
  on storage.objects for select
  using (bucket_id = 'evidence' and public.is_member(((storage.foldername(name))[1])::uuid));

create policy "editors upload screenshots"
  on storage.objects for insert
  with check (bucket_id = 'evidence' and public.can_edit(((storage.foldername(name))[1])::uuid));

create policy "editors replace screenshots"
  on storage.objects for update
  using (bucket_id = 'evidence' and public.can_edit(((storage.foldername(name))[1])::uuid));

create policy "editors delete screenshots"
  on storage.objects for delete
  using (bucket_id = 'evidence' and public.can_edit(((storage.foldername(name))[1])::uuid));
